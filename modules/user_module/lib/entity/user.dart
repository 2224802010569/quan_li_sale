class User {
  final String id;
  final String username;
  final String email;
  final String password;
  final String phone;
  final String role;
  final String fullName;
  final String groupId;

  User({
    required this.id,
    required this.username,
    required this.email,
    required this.password,
    required this.phone,
    required this.role,
    required this.fullName,
    required this.groupId,
  });
}
